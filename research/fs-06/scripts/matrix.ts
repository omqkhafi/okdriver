// Builds results/matrix.md from results/targets/*.json. No numbers are typed by hand.
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { RESULTS } from './lib/paths.ts';

const DIR = process.env.FS06_MATRIX_DIR ?? RESULTS + 'targets';
const files = readdirSync(DIR).filter((f) => f.endsWith('.json')).sort();
const T: Record<string, any> = {};
for (const f of files) T[f.replace(/\.json$/, '')] = JSON.parse(readFileSync(DIR + '/' + f, 'utf8'));

const SEQS = ['S1', 'S2', 'S2b', 'S3', 'S3i', 'S3u', 'S3ui', 'S3f', 'S4a-A', 'S4a-B', 'S4b-A', 'S4b-B', 'S4c-setup-A', 'S4c-setup-B', 'S4c', 'S5', 'S6-2', 'S6-10', 'S6-100', 'S7', 'S7b'];
const POOLERS = ['direct', 'pgbouncer', 'supavisor', 'pgdog', 'odyssey'];
const codeOf = (e: string) => e.split(' ')[0]!;
const cell = (t: any, seq: string): string => {
  if (!t) return 'n/a';
  if (t.notVerified) return 'NV';
  const s = t.seqs?.[seq];
  if (!s) return 'n/a';
  const codes = new Set<string>(Object.keys(s.errors ?? {}).map(codeOf));
  const o = s.outcomes ?? {};
  const extra: string[] = [...codes];
  for (const k of ['timeout', 'closed', 'wrong-result', 'not-run']) if (o[k]) extra.push(k === 'wrong-result' && s.wrongRow ? 'WRONG ROW' : k);
  if (s.wrongRow && !extra.includes('WRONG ROW')) extra.push('WRONG ROW');
  return `${s.ok}/${s.runs}${extra.length ? ' ' + extra.join(',') : ''}`;
};
const ids = Object.keys(T);
const byPooler = (p: string) => ids.filter((i) => (p === 'direct' ? i === 'direct' || i === 'direct-tls' : i.startsWith(p + '-')));
const label = (id: string) => (id === 'direct' ? 'direct' : id.replace(/^[a-z]+-/, ''));
const out: string[] = ['# FS-06 matrix', '', 'Generated by `scripts/matrix.ts` from `results/targets/*.json`. Every number comes from those files.', '',
  'Cell = runs that succeeded out of 5, then every SQLSTATE seen, `timeout`, `closed` (connection dropped by the pooler), or `WRONG ROW` (a row for another statement with no error). `NV` = pooler did not come up (Not verified here).', ''];

// Section 0: the matrix in brief, one row per target.
const agg = (t: any, list: string[]): string => {
  if (!t || t.notVerified) return 'NV';
  let ok = 0, total = 0; const codes = new Set<string>(); let wrong = false; let other = new Set<string>();
  for (const q of list) {
    const s = t.seqs?.[q]; if (!s) continue;
    ok += s.ok; total += s.runs; for (const e of Object.keys(s.errors ?? {})) codes.add(codeOf(e)); if (s.wrongRow) wrong = true;
    for (const k of ['timeout', 'closed']) if (s.outcomes?.[k]) other.add(k);
  }
  return `${ok}/${total}${[...codes, ...(wrong ? ['WRONG ROW'] : []), ...other].length ? ' ' + [...codes, ...(wrong ? ['WRONG ROW'] : []), ...other].join(',') : ''}`;
};
out.push('## 0. In brief', '', 'Same cell rule. `S3 pair` = S3 and S3i (named, second flush after other clients ran); `S3u pair` = S3u and S3ui (unnamed statement across the first Sync); `S4` = S4a, S4b and S4c together (name collisions between clients); `S6` = depths 2, 10 and 100; `pinned` = client runs (of 40) whose 20 transactions all stayed on one backend, in the unnamed probe / named probe; `pg` and `postgres.js` columns are the reference clients with named statements.', '',
  '| target | S1 | S2 | S2b | S3 pair | S3u pair | S3f | S4 | S5 | S6 | S7 / S7b | pinned | pg | postgres.js |', '| --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- |');
for (const id of ids) {
  const t = T[id];
  if (t.notVerified) { out.push(`| ${id} | NV | | | | | | | | | | | | |`); continue; }
  const ref = (k: string) => { const r = t.refs?.find((x: any) => x.kind === k); return r ? (r.ok !== undefined ? `${r.ok}/${r.total}${Object.keys(r.errors ?? {}).length ? ' ' + [...new Set(Object.keys(r.errors).map(codeOf))].join(',') : ''}` : 'failed') : 'n/a'; };
  out.push(`| ${id} | ${agg(t, ['S1'])} | ${agg(t, ['S2'])} | ${agg(t, ['S2b'])} | ${agg(t, ['S3', 'S3i'])} | ${agg(t, ['S3u', 'S3ui'])} | ${agg(t, ['S3f'])} | ${agg(t, ['S4a-A', 'S4a-B', 'S4b-A', 'S4b-B', 'S4c'])} | ${agg(t, ['S5'])} | ${agg(t, ['S6-2', 'S6-10', 'S6-100'])} | ${agg(t, ['S7', 'S7b'])} | ${t.pin.unnamed.clientRunsWithOnePid}/${t.pin.named.clientRunsWithOnePid} | ${ref('pg')} | ${ref('postgres')} |`);
}
out.push('');
out.push('## 1. Success and error codes per sequence', '');
for (const p of POOLERS) {
  const cols = byPooler(p); if (!cols.length) continue;
  out.push(`### ${p}`, '', `| sequence | ${cols.map(label).join(' | ')} |`, `| --- | ${cols.map(() => '---').join(' | ')} |`);
  for (const q of SEQS) out.push(`| ${q} | ${cols.map((c) => cell(T[c], q)).join(' | ')} |`);
  out.push('');
}

out.push('## 2. Round trips', '',
  'Trace = round trips counted from the client-side proxy (runs of client bytes followed by server bytes). Implied = median elapsed time divided by 40 ms (20 ms each way). Both for the same runs. `pooler-link` = median round trips on the pooler-to-Postgres side (server-side proxy), summed over the server connections used, which the 20 ms delay does not touch; it includes the pooler\'s own simple queries.', '',
  '| target | S1 trace / implied / ms | S2 | S2b | S3 | S3f | S5 | S6-100 | S7 | pooler-link S1 / S5 / S6-100 |', '| --- | --- | --- | --- | --- | --- | --- | --- | --- | --- |');
for (const id of ids) {
  const t = T[id]; if (t.notVerified) continue;
  const f = (q: string) => { const s = t.seqs[q]; if (!s?.traceRoundTrips) return 'n/a'; const tr = s.traceRoundTrips; return `${tr.min === tr.max ? tr.median : `${tr.min}-${tr.max}`} / ${s.impliedRoundTrips} / ${s.elapsedMs.median}`; };
  out.push(`| ${id} | ${['S1', 'S2', 'S2b', 'S3', 'S3f', 'S5', 'S6-100', 'S7'].map(f).join(' | ')} | ${['S1', 'S5', 'S6-100'].map((q) => t.seqs[q]?.serverTrips ?? 'n/a').join(' / ')} |`);
}
out.push('');

out.push('## 3. Did the pooler forward Parse and Bind as sent?', '',
  'Server-side proxy vs client-side proxy, per run. `as sent` = same extended-protocol messages, same statement name and SQL in Parse, same name in Bind. Notes are counts over the 5 runs.', '',
  '| target | sequence | as sent (of 5) | what changed |', '| --- | --- | --- | --- |');
for (const id of ids) {
  const t = T[id]; if (t.notVerified) continue;
  for (const q of ['S1', 'S2', 'S2b', 'S5', 'S6-10']) {
    const s = t.seqs[q]; if (!s) continue;
    if (id.startsWith('direct')) { out.push(`| ${id} | ${q} | n/a | no server-side proxy (no pooler) |`); continue; }
    const n = (Object.entries(s.serverNotes ?? {}).map(([k, v]) => `${k} (${v})`).join('; ') || 'nothing') + (s.poolerQueries?.length ? `; pooler's own queries: ${s.poolerQueries.map((x: string) => '`' + x.slice(0, 40).replace(/fs06-[a-z0-9_-]+/g, 'fs06-…') + '`').join(' ')}` : '');
    out.push(`| ${id} | ${q} | ${s.forwardedAsSent} | ${n} |`);
  }
}
out.push('');

out.push('## 4. Pinning and sharing', '',
  'Probe: 8 clients at once, 20 transactions each, per run (5 runs). `unnamed` = S1 form every time; `named` = S2 on the first transaction, S2b form (Bind only) afterwards. `pids/run` = distinct backend PIDs seen by all clients in a run. `1-pid clients` = client runs whose 20 transactions all landed on one backend. Server pool is 2 (8 in session mode).', '',
  '| target | unnamed ok | unnamed pids/run | named ok | named pids/run | 1-pid clients (unnamed / named) | named errors |', '| --- | --- | --- | --- | --- | --- | --- |');
for (const id of ids) {
  const t = T[id]; if (t.notVerified) continue;
  const u = t.pin.unnamed, n = t.pin.named;
  const errs = Object.entries(n.errors).map(([k, v]) => `${codeOf(k)}×${v}`); const merged: Record<string, number> = {};
  for (const e of errs) { const [c, v] = e.split('×'); merged[c!] = (merged[c!] ?? 0) + Number(v); }
  out.push(`| ${id} | ${u.txnsOk}/${u.txnsTotal} | ${[...new Set(u.distinctBackendPidsPerRun)].join('/')} | ${n.txnsOk}/${n.txnsTotal} | ${[...new Set(n.distinctBackendPidsPerRun)].join('/')} | ${u.clientRunsWithOnePid}/${n.clientRunsWithOnePid} of ${u.clientRuns} | ${Object.entries(merged).map(([c, v]) => `${c}×${v}`).join(', ') || 'none'} |`);
}
out.push('', 'Prepared statements left on each backend after the last run (read through the pooler, so each row is the backend that read landed on):', '', '| target | backend | statements | first names |', '| --- | --- | --- | --- |');
for (const id of ids) {
  const t = T[id]; if (t.notVerified) continue;
  for (const b of t.preparedReadbackLastRun ?? []) out.push(`| ${id} | ${b.pid} | ${b.count} | ${b.names.slice(0, 3).join(', ')} |`);
}
out.push('', 'Pooler statistics view while the 8 clients were running (busy) and idle, last run:', '', '| target | busy | idle |', '| --- | --- | --- |');
const brief = (x: any): string => {
  if (!x) return 'no view'; if (x.error) return 'error: ' + String(x.error).slice(0, 60);
  if (x.pools) return x.pools.map((p: any) => `cl_active ${p.cl_active ?? '?'}, cl_waiting ${p.cl_waiting ?? '?'}, sv_active ${p.sv_active ?? '?'}, sv_idle ${p.sv_idle ?? '?'}, sv_used ${p.sv_used ?? '?'}`).join('; ') + (x.servers ? `; servers listed ${x.servers.length}` : '');
  return Object.entries(x).map(([k, v]) => `${k.replace('supavisor_', '')}=${v}`).join(', ');
};
for (const id of ids) { const t = T[id]; if (t.notVerified) continue; out.push(`| ${id} | ${brief(t.statsBusyLastRun)} | ${brief(t.statsIdleLastRun)} |`); }
out.push('');

out.push('## 5. ParameterStatus at login', '', 'Values that differ from a direct Postgres login, or are absent there, and whether they name the pooler. Parameters present in both with the same value are not listed.', '');
const base = new Map<string, string>((T.direct?.login?.parameterStatus ?? []).map(([k, v]: [string, string]) => [k, v]));
out.push('| target | parameters not sent by direct Postgres, or with another value | application_name echo | order differs from direct | count |', '| --- | --- | --- | --- | --- |');
const baseOrder = (T.direct?.login?.parameterStatus ?? []).map(([k]: [string, string]) => k).join(',');
for (const id of ids) {
  const t = T[id]; if (t.notVerified || id.startsWith('direct')) continue;
  const ps: [string, string][] = t.login?.parameterStatus ?? [];
  const diff = ps.filter(([k, v]) => k !== 'application_name' && base.get(k) !== v).map(([k, v]) => `${k}=${v}`);
  const app = ps.find(([k]) => k === 'application_name')?.[1] ?? '(none)';
  out.push(`| ${id} | ${diff.join('; ') || 'none'} | ${app.startsWith('fs06-') ? 'echoes the client value' : `**${app}** (client sent fs06-${id}-r1-c0)`} | ${ps.map(([k]) => k).join(',') === baseOrder ? 'no' : 'yes'} | ${ps.length} (direct ${base.size}) |`);
}
out.push('');

out.push('## 6. Reference clients', '', '`pg` and `postgres` (postgres.js): 8 clients, the same statement over 20 transactions each (BEGIN, the statement, COMMIT for `pg`; `sql.begin` for postgres.js). `named` = the library\'s prepared-statement mode (pg: `name`; postgres.js: `prepare: true`), `unnamed` = text only (pg) or `prepare: false`.', '',
  '| target | pg named | pg unnamed | postgres.js named | postgres.js unnamed | error codes |', '| --- | --- | --- | --- | --- | --- |');
for (const id of ids) {
  const t = T[id]; if (t.notVerified || !t.refs) continue;
  const g = (k: string) => { const r = t.refs.find((x: any) => x.kind === k); return r ? (r.ok !== undefined ? `${r.ok}/${r.total}` : r.timeout ? 'timeout' : 'failed') : 'n/a'; };
  const codes = new Set<string>(); for (const r of t.refs) for (const e of Object.keys(r.errors ?? {})) codes.add(`${r.kind}: ${e.split(' ')[0]}`);
  out.push(`| ${id} | ${g('pg')} | ${g('pg-unnamed')} | ${g('postgres')} | ${g('postgres-unnamed')} | ${[...codes].join('; ') || 'none'} |`);
}
out.push('');

out.push('## 7. Failure messages seen', '', 'Exact SQLSTATE and message text per target and sequence, counts over 5 runs (and over the pinning probes for the last block).', '', '| target | sequence | SQLSTATE and message | times |', '| --- | --- | --- | --- |');
for (const id of ids) {
  const t = T[id]; if (t.notVerified) continue;
  for (const q of SEQS) for (const [e, n] of Object.entries(t.seqs[q]?.errors ?? {})) out.push(`| ${id} | ${q} | ${String(e).replace(/\|/g, '\\|').replace(/fs06_[a-z0-9_.-]+/g, (m) => m.replace(/^fs06_[a-z_]+-?[a-z]*-r\d_/, 'fs06_<run>_'))} | ${n} |`);
}
out.push('');
const nv = ids.filter((i) => T[i].notVerified);
if (nv.length) { out.push('## Not verified here', ''); for (const i of nv) out.push(`- ${i}: ${String(T[i].blocker).split('\n')[0]!.slice(0, 300)}`); out.push(''); }
writeFileSync(process.env.FS06_MATRIX_OUT ?? RESULTS + 'matrix.md', out.join('\n'));
console.log(`matrix.md written: ${ids.length} targets`);
